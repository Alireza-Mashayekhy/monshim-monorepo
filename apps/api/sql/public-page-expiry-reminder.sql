--
-- هدف:
--   ستون `expiry_reminder_sms_sent_at` کلید idempotency پیامک یادآوری است.
--   کرونِ `PublicPageExpiryReminderService` فقط ردیف‌هایی را می‌بیند که این
--   ستون در آن‌ها NULL است و بلافاصله پرش می‌کند؛ بنابراین هر اشتراک
--   حداکثر یک پیامک یادآوری می‌گیرد.
--
-- این فایل فقط برای محیط production لازم است؛ در بقیهٔ محیط‌ها
-- `synchronize` خود TypeORM ستون را می‌سازد.
--
-- ⚠️ ترتیب استقرار: این فایل باید **قبل از** استقرار کدِ جدید اجرا شود.
-- هیچ رکورد موجودی تغییر نمی‌کند؛ ستون جدید برای همهٔ ردیف‌های فعلی NULL
-- است، یعنی هیچ اشتراکِ در آستانهٔ انقضایی پیامک تکراری نمی‌گیرد (هر کدام
-- حداکثر یک‌بار، در اولین اجرای کرون بعد از استقرار).
--
-- نکته: اجرای دوبارهٔ این فایل خطا می‌دهد (ADD COLUMN تکراری). اگر
-- مطمئن نیستید، اول ستون را چک کنید:
--   SHOW COLUMNS FROM user_subscriptions LIKE 'expiry_reminder_sms_sent_at';

ALTER TABLE user_subscriptions
  ADD COLUMN expiry_reminder_sms_sent_at DATETIME NULL;
